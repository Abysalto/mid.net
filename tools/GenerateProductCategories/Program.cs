using System.Net.Http.Json;
using System.Text;
using System.Text.RegularExpressions;

const string Source = "https://dummyjson.com/products?limit=0&select=category";
var checkOnly = args.Contains("-check") || args.Contains("--check");

var repoRoot = FindRepoRoot(Directory.GetCurrentDirectory());
var enumPath = Path.Combine(repoRoot, "AbySalto.Mid.Domain", "Enums", "ProductCategory.cs");

using var http = new HttpClient { Timeout = TimeSpan.FromSeconds(60) };
Catalogue? catalogue = null;
for (var attempt = 1; catalogue is null; attempt++)
{
    try
    {
        catalogue = await http.GetFromJsonAsync<Catalogue>(Source)
            ?? throw new InvalidOperationException("DummyJSON returned an empty response.");
    }
    catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException && attempt < 3)
    {
        Console.Error.WriteLine($"DummyJSON request failed (attempt {attempt}/3): {ex.Message} Retrying...");
        await Task.Delay(TimeSpan.FromSeconds(2 * attempt));
    }
    catch (Exception ex) when (ex is HttpRequestException or TaskCanceledException)
    {
        Console.Error.WriteLine($"Could not reach DummyJSON after 3 attempts: {ex.Message} Nothing was changed.");
        return 2;
    }
}
if (catalogue.Products.Count != catalogue.Total)
    throw new InvalidOperationException($"Got {catalogue.Products.Count} of {catalogue.Total} products; limit=0 should return all.");

var liveSlugs = catalogue.Products.Select(p => p.Category).Distinct().Order(StringComparer.Ordinal).ToList();
Console.WriteLine($"{catalogue.Total} products, {liveSlugs.Count} categories.");

var existing = File.Exists(enumPath) ? ParseExisting(File.ReadAllText(enumPath)) : new Dictionary<string, int>();
existing.Remove("Unknown");

var entries = new List<(string Name, int Value, string Slug, bool Live)>();
foreach (var (name, value) in existing.OrderBy(kv => kv.Value))
{
    var slug = ToSlug(name);
    entries.Add((name, value, slug, liveSlugs.Contains(slug)));
}

var next = existing.Count == 0 ? 1 : existing.Values.Max() + 1;
foreach (var slug in liveSlugs.Where(s => entries.All(e => e.Slug != s)))
    entries.Add((ToName(slug), next++, slug, true));

var added = entries.Where(e => !existing.ContainsKey(e.Name)).Select(e => e.Slug).ToList();
var dropped = entries.Where(e => !e.Live).Select(e => e.Slug).ToList();

var generated = Render(entries);
var current = File.Exists(enumPath) ? File.ReadAllText(enumPath) : string.Empty;
var upToDate = Normalize(current) == Normalize(generated);

Console.WriteLine(added.Count == 0 ? "No new categories." : $"New: {string.Join(", ", added)}");
if (dropped.Count > 0)
    Console.WriteLine($"No longer used by DummyJSON (kept): {string.Join(", ", dropped)}");

if (checkOnly)
{
    Console.WriteLine(upToDate ? "ProductCategory.cs is up to date." : "ProductCategory.cs is OUT OF DATE. Run the generator.");
    return upToDate ? 0 : 1;
}

if (upToDate)
{
    Console.WriteLine("ProductCategory.cs is already up to date; nothing written.");
    return 0;
}

File.WriteAllText(enumPath, generated);
Console.WriteLine($"Wrote {Path.GetRelativePath(repoRoot, enumPath)}.");
return 0;

static Dictionary<string, int> ParseExisting(string source) =>
    Regex.Matches(source, @"^\s*(?:\[[^\]]*\]\s*)*(\w+)\s*=\s*(\d+)\s*,", RegexOptions.Multiline)
        .ToDictionary(m => m.Groups[1].Value, m => int.Parse(m.Groups[2].Value));

static string ToName(string slug)
{
    var name = string.Concat(slug.Split('-', StringSplitOptions.RemoveEmptyEntries)
        .Select(part => char.ToUpperInvariant(part[0]) + part[1..]));

    if (!Regex.IsMatch(name, "^[A-Z][A-Za-z0-9]*$") || ToSlug(name) != slug)
        throw new InvalidOperationException(
            $"Category '{slug}' can't be an enum name whose slug round-trips (got '{name}'). " +
            "Handle it by hand in ProductCategory and ProductCategoryExtensions.");
    return name;
}

static string ToSlug(string name)
{
    var sb = new StringBuilder();
    for (var i = 0; i < name.Length; i++)
    {
        if (i > 0 && char.IsUpper(name[i]))
            sb.Append('-');
        sb.Append(char.ToLowerInvariant(name[i]));
    }
    return sb.ToString();
}

static string Render(List<(string Name, int Value, string Slug, bool Live)> entries)
{
    var sb = new StringBuilder();
    sb.AppendLine("// <auto-generated>");
    sb.AppendLine("// Generated by tools/GenerateProductCategories from every product on DummyJSON (distinct categories).");
    sb.AppendLine("// Regenerate: dotnet run --project tools/GenerateProductCategories    Do not edit by hand.");
    sb.AppendLine("// Names are stored in the database as text (BasketItems/Favorites.Category): never rename or remove one.");
    sb.AppendLine("// New categories are appended; a category DummyJSON stops using is kept (marked) so stored rows stay valid.");
    sb.AppendLine("// The DummyJSON slug is derived from the name (HomeDecoration -> \"home-decoration\"), see ProductCategoryExtensions.");
    sb.AppendLine("// </auto-generated>");
    sb.AppendLine();
    sb.AppendLine("namespace AbySalto.Mid.Domain.Enums;");
    sb.AppendLine();
    sb.AppendLine("public enum ProductCategory");
    sb.AppendLine("{");
    sb.AppendLine("    // A category DummyJSON returned that this enum doesn't know yet (regenerate to add it).");
    sb.AppendLine("    Unknown = 0,");
    sb.AppendLine();
    foreach (var e in entries.OrderBy(e => e.Value))
    {
        if (!e.Live)
            sb.AppendLine("    // No longer used by any DummyJSON product; kept because stored rows may reference it.");
        sb.AppendLine($"    {e.Name} = {e.Value},");
    }
    sb.AppendLine("}");
    return sb.ToString();
}

static string Normalize(string s) => s.Replace("\r\n", "\n").Trim();

static string FindRepoRoot(string start)
{
    for (var dir = new DirectoryInfo(start); dir is not null; dir = dir.Parent)
        if (File.Exists(Path.Combine(dir.FullName, "AbySalto.Mid.sln")))
            return dir.FullName;
    throw new InvalidOperationException("Run this from inside the repository (AbySalto.Mid.sln not found).");
}

internal sealed record Catalogue(List<CatalogueProduct> Products, int Total);
internal sealed record CatalogueProduct(int Id, string Category);
